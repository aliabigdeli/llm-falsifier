import argparse
from typing import List, Tuple, Union


def parse_output_time_selection(value: str) -> Union[int, Tuple[int, int], None]:
    """
    Parse output time selection argument that can be:
    - "none": Don't include output states (returns None)
    - int: e.g., "5" or "-1"
    - tuple(int, int): e.g., "(2,8)" or "2,8"
    
    Args:
        value: String value from argparse
        
    Returns:
        Parsed value as None, int, or tuple(int, int)
        
    Raises:
        argparse.ArgumentTypeError: If the format is invalid
    """
    # Handle None case (no output states)
    if value.lower() == "none":
        return None
    
    # Try to parse as tuple: (x,y) or x,y
    if ',' in value:
        # Remove parentheses if present
        clean_value = value.strip('()')
        try:
            parts = [int(x.strip()) for x in clean_value.split(',')]
            if len(parts) == 2:
                return tuple(parts)
            else:
                raise argparse.ArgumentTypeError(f"Tuple must have exactly 2 integers, got {len(parts)}") from None
        except ValueError as e:
            raise argparse.ArgumentTypeError(f"Invalid tuple format: {value}") from e
    
    # Try to parse as int
    try:
        return int(value)
    except ValueError as e:
        raise argparse.ArgumentTypeError(f"Invalid output-time-selection: {value}. Expected int, tuple(int,int), or 'none'") from e


def create_common_parser(description: str, spec_choices: List[str], default_spec: str) -> argparse.ArgumentParser:
    """Create common argument parser with shared options."""
    parser = argparse.ArgumentParser(description=description)
    
    parser.add_argument(
        "-s", 
        "--spec", 
        type=str, 
        default=default_spec, 
        choices=spec_choices,
        help=f"Specification to analyze (default: {default_spec}). Available options: " + ", ".join(spec_choices)
    )

    parser.add_argument(
        "-o", 
        "--optimizer", 
        type=str, 
        default="DA", 
        choices=["DA", "LLM", "LLMGB", "DE", "PSO", "BH", "CMAES", "UR"],
        help="Optimizer to use (default: DA). Available options: " + ", ".join(["DA", "LLM", "LLMGB", "DE", "PSO", "BH", "CMAES", "UR"])
    )
    
    parser.add_argument(
        "--seed",
        type=int,
        default=42,
        help="Random seed for reproducible results (default: 42)"
    )
    
    parser.add_argument(
        "-m",
        "--max-budget",
        type=int,
        default=100,
        help="Maximum number of iterations/budget for optimization (default: 100)"
    )
    
    parser.add_argument(
        "-l",
        "--llm-model",
        type=str,
        default="openai/gpt-oss-20b",
        help="LLM model to use (default: openai/gpt-oss-20b)"
    )
    
    parser.add_argument(
        "-r",
        "--reasoning-effort",
        type=str,
        default="low",
        choices=["minimal", "low", "medium", "high"],
        help="Reasoning effort to use for LLM optimizers (default: low)"
    )

    parser.add_argument(
        "--llm-history",
        type=int,
        default=10,
        help="Max number of exemplars in a prompt for LLM optimizers (default: 10)"
    )

    parser.add_argument(
        "--input-descriptions",
        type=int,
        default=1,
        help="Determine how input descriptions generated for LLMGB optimizer (default: 1 (short-autogenerated) other values: 2 (long-autogenerated), 3 (long-manual))"
    )

    parser.add_argument(
        "--has-output-descriptions",
        action="store_true",
        help="Use manual output descriptions for LLMGB optimizer (default: False)"
    )

    parser.add_argument(
        "--include-stl-trans",
        action="store_true",
        help="Include STL translation in the prompt for LLMGB optimizer (default: False)"
    )

    parser.add_argument(
        "--output-time-selection",
        type=parse_output_time_selection,
        default=-1,
        help="Output time selection for LLMGB optimizer. Can be 'none' (no output states), -1 (final time only), int (e.g., 5 for intervals), or tuple (e.g., '2,8' or '(2,8)'). Default: -1"
    )

    parser.add_argument(
        "--include-critical-time",
        action="store_true",
        help="Include critical time in the output for LLMGB optimizer (default: False)"
    )

    parser.add_argument(
        "--exemplars-order",
        type=str,
        default=None,
        choices=["ascending", "descending", None],
        help="Order of exemplars in the prompt for LLM optimizers (default: None)"
    )

    return parser
